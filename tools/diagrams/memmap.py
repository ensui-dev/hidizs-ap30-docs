"""Draw a memory map (SVG, not to scale) from a Markdown table, so the table stays the only source of the numbers.

Usage:
  python3 -I tools/diagrams/memmap.py PAGE "HEADING" OUT.svg [--addr COL] [--label COL] [--size COL] [--note COL]
                                                             [--group COL]
The first table after the heading is used. Defaults: Address | Region | Size | Note | Power domain.
Rows are coloured by the group column (power domains have fixed colours, other values get a palette colour in
order of appearance); rows whose label is "reserved" are drawn thin. A label containing " · " is split over lines.
The SVG has its own light background, so it reads the same in light and dark themes on github.com and on the site.
"""
import argparse, html, re

ap = argparse.ArgumentParser()
ap.add_argument('page'); ap.add_argument('heading'); ap.add_argument('out')
ap.add_argument('--addr', default='Address'); ap.add_argument('--label', default='Region')
ap.add_argument('--size', default='Size'); ap.add_argument('--note', default='Note')
ap.add_argument('--group', default='Power domain')
a = ap.parse_args()

lines = open(a.page, encoding='utf-8').read().split('\n')
want = a.heading.strip().lstrip('#').strip()
i = next(n for n, l in enumerate(lines) if l.startswith('#') and l.lstrip('#').strip() == want)
while not lines[i].startswith('|'):
    i += 1
cells = lambda l: [c.strip() for c in l.strip().strip('|').split('|')]
head = cells(lines[i]); i += 2
rows = []
while i < len(lines) and lines[i].startswith('|'):
    rows.append(dict(zip(head, cells(lines[i])))); i += 1
for col in (a.addr, a.label):
    assert col in head, f'column {col!r} not in {head}'

FIXED = {  # fill, stroke, legend label
    'PD_HIGH': ('#fde7c4', '#c77d12', 'PD_HIGH (switchable)'),
    'PD_LOGIC': ('#d6e6fb', '#3b6fb6', 'PD_LOGIC'),
    'PD_PMU': ('#d5f0dc', '#2f8a4c', 'PD_PMU (always on)'),
    '(alias)': ('#e9e2f7', '#7457b5', 'alias (depends on core / remap)'),
}
PALETTE = [('#d6e6fb', '#3b6fb6'), ('#fde7c4', '#c77d12'), ('#d5f0dc', '#2f8a4c'), ('#e9e2f7', '#7457b5'),
           ('#fbd9d9', '#b54a4a'), ('#d9f2f2', '#2c8585')]
NONE = ('#eeeeee', '#9a9a9a', 'reserved / other')
styles, order = {}, []
def key(v):
    v = re.sub(r'[`*]', '', v or '').strip()
    k = re.sub(r'\s*\(.*\)$', '', v).strip()
    return k if k else v
def style(v):
    k = key(v)
    if not k:
        return NONE
    for f in FIXED:
        if k == f or k.startswith(f):
            if f not in order: order.append(f)
            return FIXED[f]
    if k not in styles:
        fill, stroke = PALETTE[len(styles) % len(PALETTE)]
        styles[k] = (fill, stroke, k); order.append(k)
    return styles[k]

W, X0, BW, ROW, THIN, TOP = 760, 150, 400, 40, 18, 24
boxes, y = [], TOP
for r in rows:
    parts = r[a.label].split(' · ')
    h = THIN if r[a.label].lower() == 'reserved' else ROW + 16 * (len(parts) - 1)
    boxes.append((y, h, r)); y += h
used_none = any(not key(r.get(a.group, '')) for r in rows)
legend = len({key(r.get(a.group, '')) for r in rows if key(r.get(a.group, ''))}) + used_none
H = y + 30 + 22 * ((legend + 2) // 3) + 10
esc = lambda s: html.escape(re.sub(r'[`*]', '', s), quote=True)
o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="DejaVu Sans, Arial, sans-serif">',
     '<!-- SPDX-License-Identifier: CC-BY-4.0 -->',
     f'<!-- generated by tools/diagrams/memmap.py from {esc(a.page)} "{esc(want)}"; edit the table, not this file -->',
     f'<rect width="{W}" height="{H}" rx="10" fill="#ffffff" stroke="#d0d7de"/>']
for y, h, r in boxes:
    fill, stroke, _ = style(r.get(a.group, ''))
    o.append(f'<text x="{X0-10}" y="{y+13}" font-family="DejaVu Sans Mono, monospace" font-size="12" text-anchor="end" fill="#24292f">{esc(r[a.addr])}</text>')
    if r[a.label].lower() == 'reserved':
        o.append(f'<rect x="{X0}" y="{y}" width="{BW}" height="{h}" fill="{fill}" stroke="{stroke}" stroke-dasharray="4 3"/>')
        o.append(f'<text x="{X0+BW/2}" y="{y+h/2+4}" font-size="11" text-anchor="middle" fill="#57606a">reserved</text>')
        continue
    o.append(f'<rect x="{X0}" y="{y}" width="{BW}" height="{h}" fill="{fill}" stroke="{stroke}"/>')
    parts = r[a.label].split(' · ')
    for n, part in enumerate(parts):
        if len(part) > 46: part = part[:44] + "…"
        o.append(f'<text x="{X0+10}" y="{y+17+16*n}" font-size="13" font-weight="bold" fill="#24292f">{esc(part)}</text>')
    sub = ' · '.join(x for x in (r.get(a.size, ''), r.get(a.note, '')) if x)
    if len(sub) > 60: sub = sub[:58] + '…'
    o.append(f'<text x="{X0+10}" y="{y+32+16*(len(parts)-1)}" font-size="11" fill="#57606a">{esc(sub)}</text>')
    o.append(f'<text x="{X0+BW+12}" y="{y+24}" font-size="12" fill="{stroke}">{esc(r.get(a.group, ""))}</text>')
ly = boxes[-1][0] + boxes[-1][1] + 28
items = [FIXED[k] if k in FIXED else styles[k] for k in order] + ([NONE] if used_none else [])
for n, (fill, stroke, label) in enumerate(items):
    lx = 24 + (n % 3) * 245; yy = ly + (n // 3) * 22
    o.append(f'<rect x="{lx}" y="{yy-11}" width="14" height="14" fill="{fill}" stroke="{stroke}"/>')
    o.append(f'<text x="{lx+20}" y="{yy}" font-size="12" fill="#24292f">{esc(label)}</text>')
o.append('</svg>')
open(a.out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
print(f'{a.out}: {len(rows)} rows')
